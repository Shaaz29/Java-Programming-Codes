import java.util.*;

public class switchcase {
    public static void main(String[] args) {
        switch(3){
            case 1: System.out.println("Samsung");
            break;
            case 2: System.out.println("Apple");
            break;
            case 3: System.out.println("Vivo");
            case 4: System.out.println("MI");
            break;
            default : System.out.println("Redmi");
        }
    }
}
